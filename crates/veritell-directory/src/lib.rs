//! Fetching an agent's key directory, safely.
//!
//! A signed agent names where its keys are published in `Signature-Agent`
//! (draft-ietf-webbotauth-httpsig-protocol-01, section 5.5): the value is an
//! `https` URL and the resource at that URL is a JWK Set. This crate fetches
//! such a URL for the operator's configured agents and keeps what it got.
//!
//! The URL is written by whoever runs the agent and the answer comes from
//! their server, so both are treated as hostile. The rules (the draft's
//! section 6.7, and this project's gate G11):
//!
//! - `https` only; no user information, no fragment.
//! - The host is resolved first and **every** address it resolves to is
//!   checked with [`address_allowed`]. One refused address refuses the fetch.
//!   The connection is then made to an address that was checked, not to the
//!   name again, so a second DNS answer cannot differ.
//! - Only status 200 is accepted. A redirect is a failure and is never
//!   followed.
//! - At most [`MAX_BODY_BYTES`] are read.
//! - The whole fetch has a deadline.
//! - Nothing here is called while a request waits: the caller runs it on a
//!   background thread and requests read the last result.
//!
//! FIXED BY THE PROJECT LEAD: DO NOT EDIT this file. Implement `rules.rs`,
//! `cache.rs` and `https.rs` (and further private modules if you want them).
//! Nothing may panic for any input.


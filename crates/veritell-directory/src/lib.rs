use std::fmt;
use std::net::{IpAddr, SocketAddr};
use std::time::Duration;

pub use cache::Cache;
pub use https::HttpsTransport;
pub use rules::{address_allowed, fetch_with, parse_keys, parse_url, ttl_from_cache_control};

pub use veritell_wba::Ed25519Key;

/// Longest URL accepted, in bytes.
pub const MAX_URL_BYTES: usize = 2048;
/// Largest directory accepted, in bytes.
pub const MAX_BODY_BYTES: usize = 64 * 1024;
/// Lifetime of a directory whose response gives none.
pub const DEFAULT_TTL_SECS: u64 = 3600;
/// A directory is never refreshed more often than this, whatever it asks.
pub const MIN_TTL_SECS: u64 = 300;
/// A directory is never trusted longer than this without a refresh attempt.
pub const MAX_TTL_SECS: u64 = 86_400;
/// After a failed fetch the next attempt waits this long (the draft's C.5:
/// negative results expire after no more than five minutes).
pub const RETRY_SECS: u64 = 300;
/// How long past its lifetime a directory's keys stay in use while every
/// refresh fails. The draft (6.10) says a failed fetch "MUST NOT evict a
/// cached entry"; it gives no bound, so this project sets one.
pub const MAX_STALE_SECS: u64 = 7 * 86_400;

/// A URL that passed [`parse_url`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DirectoryUrl {
    /// Lowercased. A name, an IPv4 literal, or an IPv6 literal without its
    /// brackets.
    pub host: String,
    /// 443 when the URL names none.
    pub port: u16,
    /// Path and query as written, starting with `/` (`/` when the URL has
    /// no path).
    pub path_and_query: String,
}

impl DirectoryUrl {
    /// The URL again: `https://host[:port]/path?query`. The port is left out
    /// when it is 443 and an IPv6 host gets its brackets back.
    pub fn as_string(&self) -> String {
        let host = if self.host.contains(':') { format!("[{}]", self.host) } else { self.host.clone() };
        if self.port == 443 {
            format!("https://{host}{}", self.path_and_query)
        } else {
            format!("https://{host}:{}{}", self.port, self.path_and_query)
        }
    }
}

/// What a transport hands back: one response, not followed anywhere.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Response {
    pub status: u16,
    /// The `Cache-Control` response header, if there was one.
    pub cache_control: Option<String>,
    /// The body. A transport stops reading once it holds more than the
    /// `max_bytes` it was given, so this is at most `max_bytes + 1` long,
    /// and longer than `max_bytes` exactly when the body was too large.
    pub body: Vec<u8>,
}

/// The network, as [`fetch_with`] needs it. [`HttpsTransport`] is the real
/// one; tests supply their own.
pub trait Transport {
    /// Every address `host` resolves to. For an IP literal, that address.
    fn resolve(&self, host: &str, port: u16) -> Result<Vec<IpAddr>, String>;

    /// One `GET` of `url` over TLS, connected to exactly `addr`, with the
    /// certificate checked against `url.host`. Never follows a redirect:
    /// a 3xx is returned as it is. Reads at most `max_bytes + 1` body bytes.
    /// Gives up after `timeout` in total.
    fn get(
        &self,
        addr: SocketAddr,
        url: &DirectoryUrl,
        max_bytes: usize,
        timeout: Duration,
    ) -> Result<Response, String>;
}

#[derive(Clone, Debug, PartialEq, Eq, Default)]
pub struct FetchConfig {
    /// Exact addresses (with port) the operator allows although
    /// [`address_allowed`] refuses them: an agent run on the operator's own
    /// network, or a test server. Empty by default.
    pub allow: Vec<SocketAddr>,
    /// Deadline for one fetch. Zero means [`FetchConfig::DEFAULT_TIMEOUT`].
    pub timeout: Duration,
}

impl FetchConfig {
    pub const DEFAULT_TIMEOUT: Duration = Duration::from_secs(5);
}

/// A directory that was fetched and accepted.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Fetched {
    /// At least one key, at most `veritell_wba::MAX_KEYS`, no key id twice.
    pub keys: Vec<Ed25519Key>,
    /// How long to use it, already within `MIN_TTL_SECS..=MAX_TTL_SECS`.
    pub ttl_secs: u64,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum FetchError {
    /// The URL is not acceptable; why.
    Url(String),
    /// The name did not resolve, or resolved to nothing.
    Resolve(String),
    /// The name resolved to an address that may not be fetched from.
    AddressRefused(IpAddr),
    /// Connection, TLS or read failure, or the deadline passed.
    Transport(String),
    /// Any status but 200, redirects included.
    Status(u16),
    /// The body is larger than [`MAX_BODY_BYTES`].
    TooLarge,
    /// The body is not an acceptable directory; why.
    Directory(String),
}

impl fmt::Display for FetchError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            FetchError::Url(m) => write!(f, "URL refused: {m}"),
            FetchError::Resolve(m) => write!(f, "name did not resolve: {m}"),
            FetchError::AddressRefused(ip) => write!(f, "address {ip} may not be fetched from"),
            FetchError::Transport(m) => write!(f, "fetch failed: {m}"),
            FetchError::Status(s) => write!(f, "status {s}, expected 200 (redirects are not followed)"),
            FetchError::TooLarge => write!(f, "directory larger than {MAX_BODY_BYTES} bytes"),
            FetchError::Directory(m) => write!(f, "directory refused: {m}"),
        }
    }
}

impl std::error::Error for FetchError {}

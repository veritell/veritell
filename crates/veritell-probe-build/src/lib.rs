//! Per-build probe generation and sealed reports.
//!
//! Every few minutes the gateway turns the probe template (`probe/probe.js`)
//! into a new build: identifiers renamed, marked blocks reordered, comments
//! removed, and a build key and report key map embedded. The browser sends
//! its report encrypted under a key derived from that build key and the
//! request nonce. This crate also opens such a report again.
//!
//! This raises the cost of reading the script once and replaying a canned
//! report forever. It is not a secret: the build runs on the client's
//! machine. `probe/SEALING.md` describes the browser side.
//!
//! Nothing is stored per build: everything is derived from the server secret
//! and the build id, so any gateway instance with the same secret can open a
//! report for a build made by another.
//!
//! FIXED BY THE PROJECT LEAD: DO NOT EDIT this file. Implement `build.rs`
//! and `seal.rs`. Every input to `open` is attacker-controlled: nothing may
//! panic.


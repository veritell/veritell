//! Behaviour layer: reads the summary `probe/behavior.js` sends and decides
//! what it says about the client.
//!
//! The summary is a few counts (see `probe/BEHAVIOR.md`). The rules here look
//! for input that no person produces: a form submitted with no input at all,
//! pointer paths that are ruler-straight or at constant speed, clicks that
//! land on the exact centre of their target or arrive without the pointer
//! having travelled there, keys struck at perfectly even intervals, actions
//! on a fixed timer, and the think-then-act rhythm of an LLM-driven agent.
//!
//! A summary is produced on the client's machine and can be forged. A clean
//! summary proves nothing; a summary that shows scripted input is evidence.
//!
//! FIXED BY THE PROJECT LEAD: DO NOT EDIT this file or `types.rs`. Implement
//! `parse.rs` and `rules.rs`. Every input to `parse_summary` is
//! attacker-controlled: nothing may panic.


//! Privacy Pass, from the side of the site that asks for a token and checks
//! it (the "Origin" of RFC 9577). No issuing and no attesting: the tokens
//! come from an issuer the operator has chosen to trust.
//!
//! One token type is supported: `0x0002`, Blind RSA (2048-bit), which is
//! publicly verifiable (RFC 9578, section 6). Verifying a token needs only
//! the issuer's public key.
//!
//! What a token is, and is not: it shows that an issuer the operator trusts
//! vouched for the device or account that asked for it. It says nothing
//! about who is driving that device now. The gateway therefore counts a
//! token as one answered challenge and nothing more.
//!
//! The exchange (RFC 9577):
//!
//! ```text
//! WWW-Authenticate: PrivateToken challenge="<base64url TokenChallenge>", token-key="<base64url key>"
//! Authorization: PrivateToken token="<base64url Token>"
//! ```
//!
//! ```text
//! struct {                                  struct {
//!   uint16_t token_type;       // 0x0002      uint16_t token_type;       // 0x0002
//!   opaque issuer_name<1..2^16-1>;            uint8_t nonce[32];
//!   opaque redemption_context<0..32>;         uint8_t challenge_digest[32];
//!   opaque origin_info<0..2^16-1>;            uint8_t token_key_id[32];
//! } TokenChallenge;                           uint8_t authenticator[256];
//!                                           } Token;
//! ```
//!
//! `issuer_name` and `origin_info` carry a two-byte length, big-endian;
//! `redemption_context` carries a one-byte length and is empty or 32 bytes.
//! `challenge_digest` is SHA-256 of the TokenChallenge. `token_key_id` is
//! SHA-256 of the issuer key's encoding. `authenticator` is an RSASSA-PSS
//! signature (SHA-384, MGF1 with SHA-384, 48-byte salt) over the first 98
//! bytes of the token.
//!
//! All base64url here is written with padding, as RFC 9577 requires, and
//! read with or without it.
//!

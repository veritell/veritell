mod key;
mod wire;

use std::fmt;

pub use key::IssuerKey;
pub use wire::{
    challenge_digest, redemption_context, token_challenge, token_from_authorization,
    valid_server_name, verify, www_authenticate,
};

/// The one supported token type: Blind RSA (2048-bit).
pub const TOKEN_TYPE: u16 = 0x0002;
/// Exact length of a token of that type: 2 + 32 + 32 + 32 + 256.
pub const TOKEN_BYTES: usize = 354;
/// Longest issuer or origin name.
pub const MAX_NAME_BYTES: usize = 255;
/// Longest `Authorization` value looked at.
pub const MAX_AUTHORIZATION_BYTES: usize = 2048;

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum PassError {
    /// An issuer or origin name that is not a server name
    /// (see [`valid_server_name`]).
    Name,
    /// An issuer key that is not the encoding RFC 9578 section 6.5 requires;
    /// why.
    Key(&'static str),
    /// A token that is not [`TOKEN_BYTES`] long, or an `Authorization` value
    /// that uses the scheme but carries no usable token.
    Malformed,
    /// A token of another type.
    UnknownType(u16),
    /// The token names a key that is not among the issuer keys given.
    UnknownKey,
    /// The token answers a challenge this site is not asking: another site's,
    /// another issuer's, or one whose time has passed.
    WrongChallenge,
    /// The signature does not verify.
    BadAuthenticator,
}

impl fmt::Display for PassError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            PassError::Name => f.write_str("not a server name"),
            PassError::Key(why) => write!(f, "issuer key refused: {why}"),
            PassError::Malformed => f.write_str("malformed token"),
            PassError::UnknownType(t) => write!(f, "token type {t:#06x} is not supported"),
            PassError::UnknownKey => f.write_str("token from an issuer key that is not trusted"),
            PassError::WrongChallenge => f.write_str("token for another challenge"),
            PassError::BadAuthenticator => f.write_str("token signature does not verify"),
        }
    }
}

impl std::error::Error for PassError {}

/// One challenge this site would accept an answer to right now.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Accepted {
    /// SHA-256 of the TokenChallenge.
    pub challenge_digest: [u8; 32],
    /// The key the challenge was issued for. A token must name this key:
    /// one issuer's token does not answer a challenge made for another.
    pub key_id: [u8; 32],
}

/// The fields of a token that verified.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Token {
    /// Chosen by the client, unique per token: the caller uses it to refuse
    /// a second redemption.
    pub nonce: [u8; 32],
    pub challenge_digest: [u8; 32],
    pub token_key_id: [u8; 32],
}

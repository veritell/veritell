//! Population layer: what the clients of one gateway process are doing
//! together, over a sliding window.
//!
//! Nothing in a single request tells a well-made stealth browser from a
//! person. A crowd of them still shows: one fingerprint arriving from many
//! networks at once (proxy rotation), or one network producing a new
//! fingerprint on almost every request (a farm). When a rule fires it leaves
//! a short-lived reputation entry, so later requests from the same
//! fingerprint, network or client carry the detection until it expires.
//!
//! Everything is held in this process, in bounded memory. Counts of distinct
//! things are estimates.
//!
//! FIXED BY THE PROJECT LEAD: DO NOT EDIT this file. Implement `engine.rs`
//! (and further private modules if you want them). Fingerprints, routes and
//! addresses are attacker-controlled: nothing may panic, and no input may
//! make memory grow past the bound.
//!
//! # Time
//!
//! Time is whole seconds, passed in by the caller. It is cut into slots of
//! `slot_secs`. The **current window** at time `now` is the `window_slots`
//! slots ending with the slot that contains `now`; the **previous window** is
//! the `window_slots` slots before those. An event in a slot older than the
//! previous window is forgotten. A `now` earlier than one already seen is
//! treated as the latest time seen.
//!
//! # Rules
//!
//! "Networks" and "fingerprints" below are estimated distinct counts within a
//! window; "requests" are exact counts. `warm` is true once `warmup_secs`
//! have passed since the first observation.
//!
//! | id | fires when | penalty | class hint | entry on |
//! |---|---|---|---|---|
//! | `cluster_fp_spread` | `warm`, the fingerprint's networks in the current window `cur >= spread_min_networks`, and its share of all networks grew: `cur * total_prev >= spread_growth * prev * total_cur`, where `prev` is its networks in the previous window and `total_*` are the networks seen for any fingerprint | 25 | Automated | the fingerprint |
//! | `cluster_net_fanout` | `warm`, the network's fingerprints in the current window `>= fanout_min_fingerprints`, and `fingerprints * 100 >= requests * fanout_ratio_pct` for that network | 25 | Automated | the network |
//! | `client_rejections` | the client has `>= strikes_max` strikes in the current window | 40 | Automated | the client |
//! | `route_rate_surge` | `warm`, the route's requests in the current window `>= route_min_requests` and `>= route_growth * max(prev, 1)` | 5 | none | none |
//!
//! All are in `Layer::Population`. A reputation entry lasts
//! `reputation_ttl_secs` from the last time its rule held and is not renewed
//! by requests alone.


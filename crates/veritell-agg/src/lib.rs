/// Longest fingerprint or route used as given; longer ones are cut to this
/// many bytes before hashing.
pub const MAX_KEY_BYTES: usize = 512;

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Config {
    pub slot_secs: u64,
    pub window_slots: u32,
    /// Most fingerprints, networks, clients and routes tracked, each.
    pub max_keys: usize,
    pub warmup_secs: u64,
    pub spread_min_networks: u32,
    pub spread_growth: u32,
    pub fanout_min_fingerprints: u32,
    pub fanout_ratio_pct: u32,
    pub strikes_max: u32,
    pub route_min_requests: u32,
    pub route_growth: u32,
    pub reputation_ttl_secs: u64,
    /// Key for the internal hashes. `None` draws a random one per process,
    /// which is what a gateway wants; tests fix it to be repeatable.
    pub hash_seed: Option<[u8; 16]>,
}

impl Default for Config {
    /// Provisional thresholds, to be replaced by values observed in the lab
    /// and on each site's own traffic.
    fn default() -> Self {
        Config {
            slot_secs: 10,
            window_slots: 6,
            max_keys: 20_000,
            warmup_secs: 120,
            spread_min_networks: 50,
            spread_growth: 4,
            fanout_min_fingerprints: 30,
            fanout_ratio_pct: 50,
            strikes_max: 3,
            route_min_requests: 200,
            route_growth: 5,
            reputation_ttl_secs: 600,
            hash_seed: None,
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ConfigError {
    /// `slot_secs`, `window_slots` or `max_keys` is zero.
    Zero,
    /// `slot_secs` above 3600, `window_slots` above 60 or `max_keys` above
    /// 1,000,000.
    TooLarge,
}

impl fmt::Display for ConfigError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            ConfigError::Zero => "slot_secs, window_slots and max_keys must not be zero",
            ConfigError::TooLarge => "slot_secs, window_slots or max_keys too large",
        })
    }
}

impl std::error::Error for ConfigError {}

/// One request, as the population layer sees it.
#[derive(Clone, Copy, Debug)]
pub struct Observation<'a> {
    /// Whatever the caller uses to tell client software apart.
    pub fingerprint: &'a str,
    pub ip: IpAddr,
    /// The caller's per-client binding.
    pub client: [u8; 16],
    pub route: &'a str,
}

/// The network an address belongs to: its /24 for IPv4, its /48 for IPv6.
/// An IPv4-mapped IPv6 address (`::ffff:a.b.c.d`) counts as IPv4. The first
/// byte is 4 or 6; unused bytes are zero.
pub fn network_of(ip: IpAddr) -> [u8; 8] {
    let v4 = |o: [u8; 4]| [4, o[0], o[1], o[2], 0, 0, 0, 0];
    match ip {
        IpAddr::V4(a) => v4(a.octets()),
        IpAddr::V6(a) => match a.to_ipv4_mapped() {
            Some(m) => v4(m.octets()),
            None => {
                let o = a.octets();
                [6, o[0], o[1], o[2], o[3], o[4], o[5], 0]
            }
        },
    }
}

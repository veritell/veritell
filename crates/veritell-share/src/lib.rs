//! Opt-in sharing between installs: what one gateway has seen behaving as
//! automation, told to another, without telling it who.
//!
//! Off unless configured, at both ends. The parties agree two things out of
//! band: a secret ([`ShareKey`]) that makes their hashes comparable to each
//! other and to nobody else, and the sender's signing key.
//!
//! What leaves the process is a list of `(hash, class)`:
//!
//! - `hash` is the first 16 bytes of HMAC-SHA-256, keyed with the shared
//!   secret, over the 30 bytes `veritell share fingerprint v1` and one zero
//!   byte, followed by the fingerprint text. Without the secret a hash
//!   cannot be tied to a fingerprint, not even by trying known ones.
//! - `class` is `automated` or `malicious`.
//!
//! No address, no network, no User-Agent, no fingerprint text, no count and
//! no time of any request is in it (gate G10). A fingerprint is only listed
//! once it has been seen from at least `min_networks` different networks,
//! so an entry never describes one household or one person's device.
//!
//! What arrives is only ever a hint: [`Imported::detection`] carries
//! [`PENALTY`] points and no class. It cannot block by itself.
//!
//! The list travels in a `veritell-feed` bundle (signed, versioned,
//! expiring) holding one file, [`FILE_NAME`]:
//!
//! ```json
//! {"v":1,"entries":[{"h":"<32 lowercase hex digits>","c":"automated"}, ...]}
//! ```
//!
//! FIXED BY THE PROJECT LEAD: DO NOT EDIT this file. Implement `ledger.rs`
//! and `bundle.rs` (and further private modules if you want them). Bundles
//! and fingerprints are attacker-controlled: nothing may panic, and no input
//! may make memory grow past the stated bounds.

mod bundle;
mod ledger;

use std::fmt;

use veritell_core::Class;

pub use bundle::{decode, encode, open_bundle, seal_bundle, Imported};
pub use ledger::{Ledger, ShareKey};

/// The one file a share bundle holds.
pub const FILE_NAME: &str = "share_v1.json";
/// Bytes of a fingerprint hash.
pub const HASH_BYTES: usize = 16;
/// Shortest shared secret, in bytes.
pub const MIN_SECRET_BYTES: usize = 32;
/// Most entries in one bundle, and so in one imported set.
pub const MAX_ENTRIES: usize = 100_000;
/// The detection an imported entry produces.
pub const DETECTION_ID: &str = "shared_fp_reported";
/// Its penalty. Small on purpose: another install's judgement is a hint.
pub const PENALTY: u8 = 10;
/// `min_networks` may not be set below this.
pub const MIN_NETWORKS_FLOOR: u32 = 5;

/// One shared judgement.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Entry {
    pub hash: [u8; HASH_BYTES],
    /// `Class::Automated` or `Class::Malicious`, nothing else.
    pub class: Class,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Config {
    /// A fingerprint is exported once this many different networks sent it.
    pub min_networks: u32,
    /// Most fingerprints remembered.
    pub max_fingerprints: usize,
    /// A fingerprint not seen for this long is forgotten.
    pub ttl_secs: u64,
}

impl Default for Config {
    fn default() -> Self {
        Config { min_networks: 20, max_fingerprints: 50_000, ttl_secs: 86_400 }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ConfigError {
    /// `min_networks` below [`MIN_NETWORKS_FLOOR`], or `max_fingerprints` or
    /// `ttl_secs` zero.
    TooSmall,
    /// `min_networks` above 1000 or `max_fingerprints` above [`MAX_ENTRIES`].
    TooLarge,
}

impl fmt::Display for ConfigError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            ConfigError::TooSmall => "min_networks below 5, or max_fingerprints or ttl_secs zero",
            ConfigError::TooLarge => "min_networks above 1000 or max_fingerprints above 100000",
        })
    }
}

impl std::error::Error for ConfigError {}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ShareError {
    /// The bundle did not pass `veritell-feed` (signature, key, expiry,
    /// version, size, shape).
    Bundle(veritell_feed::FeedError),
    /// The bundle verified but does not hold exactly one file named
    /// [`FILE_NAME`].
    Files,
    /// The file is not the documented JSON; why.
    Format(&'static str),
    /// More than [`MAX_ENTRIES`] entries.
    TooMany,
}

impl fmt::Display for ShareError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            ShareError::Bundle(e) => write!(f, "{e}"),
            ShareError::Files => write!(f, "bundle does not hold exactly {FILE_NAME}"),
            ShareError::Format(why) => write!(f, "{FILE_NAME}: {why}"),
            ShareError::TooMany => write!(f, "more than {MAX_ENTRIES} entries"),
        }
    }
}

impl std::error::Error for ShareError {}

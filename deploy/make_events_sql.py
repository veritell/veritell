#!/usr/bin/env python3
"""Writes, from the DDL in veritell-events, so that the kit's table is the one
the gateway writes to:

  clickhouse/events.sql   CREATE TABLE, run once on an empty data folder
  clickhouse/migrate.sql  one ADD COLUMN IF NOT EXISTS per column, run by
                          migrate.sh on every update, so a column added to the
                          gateway is added to an existing table before the
                          gateway starts writing it

Columns are only ever added. A column removed from the DDL stays in the table
(migrate.sh lists such columns), and a changed type is not applied: both need
a hand-written step. Run by build.sh."""
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))


def ddl():
    src = open(os.path.join(here, "..", "crates", "veritell-events", "src", "clickhouse.rs")).read()
    m = re.search(r'pub const DDL: &str = "\\\n(.*?)";', src, re.S)
    if not m:
        sys.exit("DDL not found in veritell-events")
    return m.group(1).replace("{database}", "veritell").replace("{table}", "events").strip()


def columns(text):
    body = text[text.index("(") + 1:text.index("\n)")]
    out = []
    for line in body.split("\n"):
        line = line.strip().rstrip(",")
        if line:
            out.append(line)
    return out


def main():
    text = ddl()
    cols = columns(text)
    names = [c.split()[0] for c in cols]
    if len(set(names)) != len(names):
        sys.exit("a column appears twice in the DDL")
    with open(os.path.join(here, "clickhouse", "events.sql"), "w") as f:
        f.write("-- Generated by deploy/make_events_sql.py from veritell-events. Do not edit.\n")
        f.write(text.rstrip(";") + ";\n")
    with open(os.path.join(here, "clickhouse", "migrate.sql"), "w") as f:
        f.write("-- Generated by deploy/make_events_sql.py from veritell-events. Do not edit.\n")
        f.write("-- Adds any column the table lacks; changes nothing that exists.\n")
        for c in cols:
            f.write("ALTER TABLE veritell.events ADD COLUMN IF NOT EXISTS %s;\n" % c)


if __name__ == "__main__":
    main()
